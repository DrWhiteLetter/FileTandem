import '@vscode/codicons/dist/codicon.css';
import { createRoot } from 'react-dom/client';
import { BrowserApp } from './BrowserApp.jsx';
import { App } from './App.jsx';
import './style.css';
const bridge = acquireVsCodeApi();
const sessionId = document.querySelector('meta[name="xscp-session"]').content;
const initialState = JSON.parse(document.getElementById('xscp-state')?.textContent ?? 'null');
const Component = document.querySelector('meta[name="xscp-mode"]')?.content === 'browser' ? BrowserApp : App;
createRoot(document.getElementById('root')).render(<Component bridge={bridge} sessionId={sessionId} initialState={initialState} />);
